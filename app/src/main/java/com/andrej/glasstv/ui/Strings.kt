    /** The parts of the day, in DayPart's order, for the Dynamic Wallpaper saver's caption. */
    val dayParts: List<String>,
    val saverClock: String,
    val clockBig: String,
    val clockSmall: String,
    val sounds: String,
    val language: String,
    val choose: String,
    /** The last row of the inputs menu, which unfolds the rest of them. */
    val more: String,
    /** Shown in the screen saver picker once OK has chosen one. */
    val chosen: String,
    val on: String,
    val off: String,
    val moveHint: String,
    val previewHint: String,
    /** Screen saver id -> name. */
    val savers: Map<String, String>,
    val controlCenter: String,
    val powerOff: String,
    val performance: String,
    val sound: String,
    /** The control center's button back to the app used before. */
    val lastApp: String,
    /** The control center's ambient light (the LED strip behind the TV) and its colour. */
    val ambientLight: String,
    val lightColor: String,
    /** The light's colours, in AmbientLight.COLORS's order (the strip's own first), then the household's own (CUSTOM). */
    val lightColors: List<String>,
    /** Shown while the colour tile is being adjusted. */
    val colorHint: String,
    /** The light without Glass allowed Bluetooth, and the strip not answering. */
    val needsBluetooth: String,
    val stripAway: String,
    /** Wi-Fi with no name to show (Glass may not read it), and no network at all. */
    val connected: String,
    val offline: String,
    val ethernet: String,
    /** A tile with nothing to do (the light out of reach). */
    val unavailable: String,
    val volume: String,
    val muted: String,
    /** Shown while the sound tile is being adjusted. */
    val volumeHint: String,
    /** Power Off without Glass's accessibility service, which is what puts the TV to sleep. */
    val needsService: String,
    /** The quick settings (the TCL remote's button right of 0). */
    val quickSettings: String,
    val picture: String,
    /** The picture presets, in PictureMode's order. */
    val pictureModes: List<String>,
    /**
     * The sound modes, by the number TCL keeps for each in `tcl_sys_audio_sound_mode` on this TV, as
     * read off its sound pop-up on 2026-10-31: Standard 0, Movie 1, Music 2, Voice 3, Game 4, Sport 5,
     * Intelligent 7 (6 is none of this TV's modes).
     */
    val soundModes: List<String>,
    val game: String,
    val brightness: String,
    val speakers: String,
    val sleepTimer: String,
    /** The sleep timer's choices, in SleepTimer.CHOICES's order (Off last). */
    val sleepChoices: List<String>,
    /** The rest of TCL's Quick Settings: its game mode, HDMI-CEC (T-Link), and the screens it opens. */
    val gameMaster: String,
    /** Game Master's third setting, beside on and off. */
    val auto: String,
    val cec: String,
    val network: String,
    val pictureSettings: String,
    val displaySound: String,
    /** The card on the TV while the iPhone app pairs: its title, and where the code goes. */
    val pairTitle: String,
    val pairHint: String,
)

